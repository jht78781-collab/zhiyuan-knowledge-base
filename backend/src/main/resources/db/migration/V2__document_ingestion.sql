CREATE TABLE kb_document (
    id BIGINT NOT NULL AUTO_INCREMENT,
    knowledge_base_id BIGINT NOT NULL,
    uploaded_by BIGINT NOT NULL,
    original_name VARCHAR(240) NOT NULL,
    object_key VARCHAR(120) NOT NULL,
    remote_name VARCHAR(80) NOT NULL,
    byte_size BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    storage_ready BOOLEAN NOT NULL DEFAULT FALSE,
    delete_requested BOOLEAN NOT NULL DEFAULT FALSE,
    remote_write_attempted BOOLEAN NOT NULL DEFAULT FALSE,
    remote_id VARCHAR(80),
    remote_batch VARCHAR(120),
    error_message VARCHAR(240),
    next_attempt_at DATETIME(6),
    index_started_at DATETIME(6),
    attempts INT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_doc_object UNIQUE (object_key),
    CONSTRAINT uq_doc_remote_name UNIQUE (remote_name),
    CONSTRAINT uq_doc_remote_id UNIQUE (knowledge_base_id, remote_id),
    CONSTRAINT fk_doc_kb FOREIGN KEY (knowledge_base_id) REFERENCES kb_knowledge_base (id),
    CONSTRAINT fk_doc_user FOREIGN KEY (uploaded_by) REFERENCES sys_user (id),
    INDEX ix_doc_visible (knowledge_base_id, status, id),
    INDEX ix_doc_due (next_attempt_at, id)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
